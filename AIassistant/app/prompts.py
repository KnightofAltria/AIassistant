# ---------------------------------------------------------------- 回答风格
# 前端下拉框的 value 直接对应这里的 key；未命中的一律回落 concise。
STYLE_SUFFIX = {
    "concise": """\n\n【风格：简明】先用 3~5 行给结论和关键点，能一句说清就不写第二句。
不需要展开推导，除非用户明确要求。""",
    "detailed": """\n\n【风格：详解】按"结论 → 为什么 → 推导/例子 → 易错点"展开，
可以写长一点，但每一段都要有信息增量，不要复述。""",
    "socratic": """\n\n【风格：苏格拉底式】不要直接给出完整答案。先用一个反问或小问题引导学生自己推导，
再根据他的回答逐步补足。每轮最多给一条关键提示，并在结尾留一个问题。""",
}


def chat_system(style: str = "concise") -> str:
    return CHAT_SYSTEM + STYLE_SUFFIX.get(style, STYLE_SUFFIX["concise"])


